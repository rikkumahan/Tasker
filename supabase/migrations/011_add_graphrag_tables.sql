-- ─────────────────────────────────────────────
-- 11. RPC: match_contacts
-- Semantic nearest-neighbour search on contacts.embedding.
-- Used by GraphRAGStore.resolveContact() for entity resolution.
-- ─────────────────────────────────────────────
CREATE OR REPLACE FUNCTION match_contacts(
  query_embedding  vector(1536),
  match_threshold  float    DEFAULT 0.85,
  match_count      int      DEFAULT 5
)
RETURNS TABLE (
  id            uuid,
  email         text,
  name          text,
  organization  text,
  bio_summary   text,
  similarity    float
)
LANGUAGE plpgsql STABLE SECURITY DEFINER
AS $$
BEGIN
  RETURN QUERY
  SELECT
    c.id,
    c.email,
    c.name,
    c.organization,
    c.bio_summary,
    1 - (c.embedding <=> query_embedding) AS similarity
  FROM contacts c
  WHERE c.embedding IS NOT NULL
    AND 1 - (c.embedding <=> query_embedding) >= match_threshold
  ORDER BY c.embedding <=> query_embedding
  LIMIT match_count;
END;
$$;

