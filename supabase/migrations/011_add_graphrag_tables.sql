  target_type       text        NOT NULL,
  relationship_type text        NOT NULL,  -- 'SENT_BY' | 'ASSIGNED_TO' | 'PART_OF' etc.
  description       text        NOT NULL,
  created_at        timestamptz DEFAULT now()
);

