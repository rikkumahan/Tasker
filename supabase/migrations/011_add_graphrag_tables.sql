-- ─────────────────────────────────────────────
-- 14. RPC: get_entity_neighborhood
-- Returns 1-hop neighbors of a given node.
-- Exposed as an LLM tool for context-aware action-insight tracking.
-- ─────────────────────────────────────────────
CREATE OR REPLACE FUNCTION get_entity_neighborhood(
  seed_node_id    uuid,
  max_hops        int  DEFAULT 1,
  max_neighbors   int  DEFAULT 20
)
RETURNS TABLE (
  node_id           uuid,
  node_type         text,
  relationship_type text,
  direction         text,   -- 'outbound' | 'inbound'
  description       text
)
LANGUAGE plpgsql STABLE SECURITY DEFINER
AS $$
BEGIN
  RETURN QUERY
  -- Outbound edges
  SELECT
    ge.target_id        AS node_id,
    ge.target_type      AS node_type,
    ge.relationship_type,
    'outbound'::text    AS direction,
    ge.description
  FROM graph_edges ge
  WHERE ge.source_id = seed_node_id
  UNION ALL
  -- Inbound edges
  SELECT
    ge.source_id        AS node_id,
    ge.source_type      AS node_type,
    ge.relationship_type,
    'inbound'::text     AS direction,
    ge.description
  FROM graph_edges ge
  WHERE ge.target_id = seed_node_id
  LIMIT max_neighbors;
END;
$$;

-- ─────────────────────────────────────────────
-- 15. RPC: find_path_between_entities
-- BFS-style 2-hop path finder between two entity nodes.
-- Exposed as an LLM tool for relational reasoning.
-- ─────────────────────────────────────────────
CREATE OR REPLACE FUNCTION find_path_between_entities(
  source_node_id  uuid,
  target_node_id  uuid
)
RETURNS TABLE (
  hop             int,
  node_id         uuid,
  node_type       text,
  relationship_type text,
  description     text
)
LANGUAGE plpgsql STABLE SECURITY DEFINER
AS $$
BEGIN
  RETURN QUERY
  WITH RECURSIVE path_cte AS (
    -- Seed: direct connections from source
    SELECT
      1                     AS hop,
      ge.target_id          AS node_id,
      ge.target_type        AS node_type,
      ge.relationship_type,
      ge.description,
      ARRAY[source_node_id, ge.target_id] AS visited
    FROM graph_edges ge
    WHERE ge.source_id = source_node_id

    UNION ALL

    -- Expand one more hop
    SELECT
      p.hop + 1,
      ge.target_id,
      ge.target_type,
      ge.relationship_type,
      ge.description,
      p.visited || ge.target_id
    FROM path_cte p
    JOIN graph_edges ge ON ge.source_id = p.node_id
    WHERE p.hop < 2
      AND NOT (ge.target_id = ANY(p.visited))  -- no cycles
  )
  SELECT hop, node_id, node_type, relationship_type, description
  FROM path_cte
  WHERE node_id = target_node_id
  ORDER BY hop
  LIMIT 10;
END;
$$;

-- ─────────────────────────────────────────────
-- 16. RPC: get_entity_timeline
-- Returns all edges for a node ordered by creation date.
-- Exposed as an LLM tool for timeline/history queries.
-- ─────────────────────────────────────────────
CREATE OR REPLACE FUNCTION get_entity_timeline(
  entity_id   uuid,
  limit_rows  int  DEFAULT 20
)
RETURNS TABLE (
  edge_id           uuid,
  relationship_type text,
  direction         text,
  counterpart_id    uuid,
  counterpart_type  text,
  description       text,
  created_at        timestamptz
)
LANGUAGE plpgsql STABLE SECURITY DEFINER
AS $$
BEGIN
  RETURN QUERY
  SELECT
    ge.id               AS edge_id,
    ge.relationship_type,
    CASE WHEN ge.source_id = entity_id THEN 'outbound' ELSE 'inbound' END AS direction,
    CASE WHEN ge.source_id = entity_id THEN ge.target_id ELSE ge.source_id END AS counterpart_id,
    CASE WHEN ge.source_id = entity_id THEN ge.target_type ELSE ge.source_type END AS counterpart_type,
    ge.description,
    ge.created_at
  FROM graph_edges ge
  WHERE ge.source_id = entity_id OR ge.target_id = entity_id
  ORDER BY ge.created_at DESC
  LIMIT limit_rows;
END;
$$;
