  id            uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
  email         text        UNIQUE NOT NULL,
  name          text,
  organization  text,
  bio_summary   text,
  embedding     vector(1536),
  created_at    timestamptz DEFAULT now()
);

-- ─────────────────────────────────────────────
-- 2. PROJECTS
-- Represents focus areas / business initiatives
-- ─────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS projects (
  id          uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
  name        text        UNIQUE NOT NULL,
  description text,
  status      text        DEFAULT 'active',
  created_at  timestamptz DEFAULT now()
);

-- ─────────────────────────────────────────────
-- 3. THREADS
-- Groups related email messages under one Gmail thread
-- ─────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS threads (
  id              uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
  gmail_thread_id text        UNIQUE NOT NULL,
  subject         text,
  semantic_summary text,
  project_id      uuid        REFERENCES projects(id) ON DELETE SET NULL,
  created_at      timestamptz DEFAULT now()
);

-- ─────────────────────────────────────────────
-- 4. EMAILS
-- Individual email messages (children of threads)
-- ─────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS emails (
  id          uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
  message_id  text        UNIQUE NOT NULL,
  thread_id   uuid        REFERENCES threads(id)   ON DELETE CASCADE,
  sender_id   uuid        REFERENCES contacts(id)  ON DELETE RESTRICT,
  subject     text,
  body        text,
  snippet     text,
  received_at timestamptz NOT NULL,
  embedding   vector(1536),
  created_at  timestamptz DEFAULT now()
);

-- ─────────────────────────────────────────────
-- 5. COMMUNITY REPORTS
-- Louvain cluster summaries generated by the LLM
-- ─────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS community_reports (
  id                  uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
  title               text        NOT NULL,
  summary             text        NOT NULL,
  rating              numeric     NOT NULL,
  rating_explanation  text        NOT NULL,
  findings            jsonb       NOT NULL DEFAULT '[]'::jsonb,
  embedding           vector(1536),
  created_at          timestamptz DEFAULT now()
);

-- ─────────────────────────────────────────────
-- 6. COMMUNITY MEMBERS
-- Maps graph nodes (entities) to their community cluster
-- ─────────────────────────────────────────────
